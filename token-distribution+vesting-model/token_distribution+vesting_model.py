plt.stackplot(arb.index, arb_parts.T.values / 1e6, labels=arb_parts.columns)
plt.axvline(12, color="black", linestyle="--")
plt.xlabel("Month")
plt.ylabel("Circulating supply (M ARB)")
plt.title("ARB circulating supply by bucket (treasury excluded)")
plt.legend(loc="upper left")
plt.show()

plt.figure(figsize=(10, 4))
plt.plot(arb.index[1:], arb["Inflation"].iloc[1:])
plt.axvline(12, color="black", linestyle="--")
plt.xlabel("Month")
plt.ylabel("Monthly inflation (%)")
plt.title("ARB monthly supply inflation")
plt.show()

arb_prices.plot(figsize=(10, 5), title="ARB price index by sell scenario")
