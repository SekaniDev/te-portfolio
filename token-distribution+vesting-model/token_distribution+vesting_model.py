print((show / [1e6, 1]).round(2))

arb_low = {"Team": 0.10, "Investors": 0.30, "Airdrops": 0.0, "Foundation": 0.0}
arb_base = {"Team": 0.20, "Investors": 0.50, "Airdrops": 0.0, "Foundation": 0.05}
arb_high = {"Team": 0.50, "Investors": 0.70, "Airdrops": 0.0, "Foundation": 0.10}

arb_scenarios = {"Low": arb_low, "Base": arb_base, "High": arb_high}

arb_parts = arb[list(arb_buckets.keys())]
