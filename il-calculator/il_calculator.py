"""Fees vs IL"""

def liquidity_multiplier(p0, pa, pb):
    L3 = 1.0 / v3_value_per_L(p0, pa, pb)
    L2 = 1.0 / (2 * np.sqrt(p0))
    return L3 / L2

def net_return(p0, p1, pa, pb, fee_v2):
    """Net return vs HODL: IL + fees. fee_v2 = fee return a v2 LP earns over the period."""
    p1 = np.asarray(p1, dtype=float)
    m = liquidity_multiplier(p0, pa, pb)
    in_range = (p1 >= pa) & (p1 <= pb)
    v3 = il_v3(p0, p1, pa, pb) + np.where(in_range, fee_v2 * m, 0.0)
    v2 = il_v2(p1 / p0) + fee_v2
    return v2, v3

p0, fee_v2 = 1.0, 0.03   # assume 3% fee return for v2 over the period
p1 = np.linspace(0.3, 3, 600)

for pa, pb in [(0.9, 1.1), (0.5, 2), (0.1, 10)]:
    print(f"[{pa}, {pb}] multiplier = {liquidity_multiplier(p0, pa, pb):.1f}x")

v2, _ = net_return(p0, p1, 0.9, 1.1, fee_v2)
plt.plot(p1, v2 * 100, "k--", label="v2")
for pa, pb in [(0.9, 1.1), (0.5, 2), (0.1, 10)]:
    _, v3 = net_return(p0, p1, pa, pb, fee_v2)
    plt.plot(p1, v3 * 100, label=f"v3 [{pa}, {pb}]")

plt.axhline(0, color="gray", lw=0.5)
plt.xlabel("End price (start = 1)")
plt.ylabel("Net return vs HODL (%)")
plt.legend()
plt.title(f"Fees + IL, v2 fee return = {fee_v2:.0%}")
plt.show()

