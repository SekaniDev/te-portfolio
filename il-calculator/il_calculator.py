import numpy as np
import matplotlib.pyplot as plt

def v3_value_per_L(p, pa, pb):
    p = np.asarray(p, dtype=float)
    sp = np.sqrt(np.clip(p, pa, pb))
    x = 1 / sp - 1 / np.sqrt(pb)   # base token per unit L
    y = sp - np.sqrt(pa)           # quote token per unit L
    return x * p + y

def il_v3(p0, p1, pa, pb):
    p1 = np.asarray(p1, dtype=float)
    L = 1.0 / v3_value_per_L(p0, pa, pb)      # normalise start value to 1
    lp = L * v3_value_per_L(p1, pa, pb)
    sp0 = np.sqrt(p0)
    x0 = L * (1 / sp0 - 1 / np.sqrt(pb))
    y0 = L * (sp0 - np.sqrt(pa))
    hodl = x0 * p1 + y0
    return lp / hodl - 1

p0 = 1.0
p1 = np.linspace(0.3, 3, 600)

# Plot v2 vs v3
